#!/usr/bin/env python3
"""Generate icons.js from the Material Icons font that the Flutter app uses.

Usage:
    python tools/make_icons.py [PATH_TO_materialicons-regular.otf]

The app draws its icons with Flutter's bundled Material Icons font
(Icons.castle_rounded and so on). This script extracts the same glyphs as
SVG path data so the web version shows identical icons without loading an
icon font. With no argument it looks for the font in the Flutter SDK found
on PATH (bin/cache/artifacts/material_fonts). Needs fontTools.

Material Icons are licensed under the Apache License 2.0.
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

# web name -> Flutter Icons name (the codepoints file uses *_baseline for the
# plain style).
ICONS = {
    "ancient": "account_balance_rounded",
    "medieval": "castle_rounded",
    "early_modern": "sailing_rounded",
    "modern1": "factory_rounded",
    "contemporary": "public_rounded",
    "person": "person_rounded",
    "year": "calendar_month_rounded",
    "event": "flag_rounded",
    "notifications": "notifications_none_rounded",
    "settings": "settings_rounded",
    "trophy": "emoji_events_rounded",
    "chevron_right": "chevron_right_rounded",
    "arrow_back": "arrow_back_baseline",
    "star": "star_baseline",
    "star_rounded": "star_rounded",
    "star_outline": "star_outline_rounded",
    "lock": "lock_baseline",
    "play": "play_arrow_rounded",
    "trending_up": "trending_up_rounded",
    "lightbulb": "lightbulb_rounded",
    "check": "check_rounded",
    "close": "close_rounded",
    "menu_book": "menu_book_rounded",
    "arrow_forward": "arrow_forward_rounded",
    "flag": "flag_rounded",
    "refresh": "refresh_rounded",
    "privacy": "privacy_tip_outlined",
    "reset": "restart_alt_rounded",
    "phone": "phone_android_rounded",
    "open_in_new": "open_in_new_rounded",
    "info": "info_outline_rounded",
    "language": "language_rounded",
    "keyboard": "keyboard_rounded",
}

WEB_ROOT = Path(__file__).resolve().parent.parent


def find_font() -> Path:
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    flutter = shutil.which("flutter")
    if not flutter:
        sys.exit("flutter not on PATH; pass the path to materialicons-regular.otf")
    return (Path(flutter).resolve().parent / "cache" / "artifacts" /
            "material_fonts" / "materialicons-regular.otf")


def main() -> None:
    font_path = find_font()
    codepoints = {}
    for line in (font_path.parent / "codepoints").read_text().splitlines():
        name, _, cp = line.partition(" ")
        codepoints[name] = int(cp, 16)

    font = TTFont(str(font_path))
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()

    out = {}
    for web_name, flutter_name in ICONS.items():
        glyph = cmap[codepoints[flutter_name]]
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:g}")
        # Font units are y-up with the baseline at 0; SVG is y-down.
        glyphs[glyph].draw(TransformPen(pen, (1, 0, 0, -1, 0, upm)))
        out[web_name] = pen.getCommands()

    body = json.dumps(out, indent=1, sort_keys=True)
    js = (
        "// Generated by tools/make_icons.py from Flutter's Material Icons font\n"
        "// (Apache License 2.0). Do not edit by hand.\n"
        f"// viewBox: 0 0 {upm} {upm}\n"
        f"window.ICON_VIEWBOX = '0 0 {upm} {upm}';\n"
        f"window.ICONS = {body};\n"
    )
    (WEB_ROOT / "icons.js").write_text(js, encoding="utf-8", newline="\n")
    print(f"icons.js: {len(out)} icons")


if __name__ == "__main__":
    main()
